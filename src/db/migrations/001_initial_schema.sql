CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL,
  password_hash text NOT NULL,
  full_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique
  ON public.users (lower(email));

CREATE TABLE IF NOT EXISTS public.cameras (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  name text NOT NULL,
  source_type text NOT NULL CHECK (source_type IN ('rtsp', 'webcam')),
  rtsp_url_enc text,
  status text NOT NULL DEFAULT 'offline' CHECK (status IN ('online', 'offline', 'error')),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (source_type = 'rtsp' AND rtsp_url_enc IS NOT NULL)
    OR (source_type = 'webcam' AND rtsp_url_enc IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS cameras_user_id_idx
  ON public.cameras (user_id);

CREATE TABLE IF NOT EXISTS public.incidents (
  alert_id text PRIMARY KEY,
  detection_time timestamptz NOT NULL,
  alert_time timestamptz,
  parent_response text NOT NULL DEFAULT 'Pending',
  outcome text NOT NULL,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  camera_id uuid REFERENCES public.cameras(id) ON DELETE SET NULL,
  location_lat double precision CHECK (location_lat IS NULL OR location_lat BETWEEN -90 AND 90),
  location_lng double precision CHECK (location_lng IS NULL OR location_lng BETWEEN -180 AND 180),
  escalation_level integer NOT NULL DEFAULT 1 CHECK (escalation_level BETWEEN 1 AND 3)
);

CREATE INDEX IF NOT EXISTS incidents_user_detection_time_idx
  ON public.incidents (user_id, detection_time DESC);

CREATE TABLE IF NOT EXISTS public.escalation_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  alert_id text NOT NULL REFERENCES public.incidents(alert_id) ON DELETE CASCADE,
  level integer NOT NULL CHECK (level BETWEEN 1 AND 3),
  action text NOT NULL,
  due_at timestamptz,
  done_at timestamptz,
  claimed_at timestamptz,
  attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  detail text
);

CREATE UNIQUE INDEX IF NOT EXISTS escalation_events_alert_action_due_unique
  ON public.escalation_events (alert_id, action)
  WHERE due_at IS NOT NULL;

CREATE INDEX IF NOT EXISTS escalation_events_due_idx
  ON public.escalation_events (due_at)
  WHERE done_at IS NULL AND due_at IS NOT NULL;
